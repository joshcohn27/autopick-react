// Our own ADP ranking, capped at 400 players. Built from:
//   - A self-pulled ESPN live-draft-results snapshot (fresh, not a beatadp.com
//     scrape) for the top ~250 players, blended with existing Sleeper PPR data
//     where both existed.
//   - Our own sheet's position rank lists (2026 Players Background Eqs) for
//     everyone else, cross-checked against real August 24, 2026 depth charts.
// Two structural fixes applied after the raw merge produced bad results:
//   - QB is capped at exactly the 32 real Week 1 starters (verified against live
//     depth charts) since this is a single-QB league -- backups have essentially
//     zero standard-league value regardless of draft-capital hype. 5 names with
//     early ADP got dropped for being backups (Shedeur Sanders, J.J. McCarthy,
//     Tommy DeVito, Drew Allar, Fernando Mendoza); 5 real starters missing from
//     the raw pull got added back (Jacoby Brissett, Tua Tagovailoa, Deshaun
//     Watson, Kirk Cousins, Geno Smith).
//   - The RB/WR/TE deep tail (players with no real market ADP, filled from our
//     own sheet) is interleaved round-robin across those three positions, not
//     processed as sequential blocks -- the original block approach silently
//     favored whichever position got processed first, producing nonsense like
//     170 RBs and 88 WRs. Round-robin fixed that.
// No free agents (nflTeam: 'FA' entries removed entirely, checked at every merge
// stage). K/DST sit at a 'round 12 or later' floor ((12-1)*14+1 = 155 for a
// 14-team league) as a hard minimum, enforced even against real ADP that came in
// earlier than that -- their real relative order is preserved above the floor,
// they're just not allowed to sort earlier than round 12 as a group.

